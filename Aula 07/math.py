from os import system
import math
system("cls");

# help = verifica funcionalidades do módulo MATH
# help#math

# ceil = sempre irá arredondar para cima
print(math.ceil(5.1));

# floor = sempre irá arredondar para baixo
print(math.floor(5.9));

# fabs = valor absoluto
print(math.fabs(-8));

# fmod = retorna o resto da divisão
print(math.fmod(5, 2));

# sqrt = retorna a raiz quadrada de um número
print(math.sqrt(25));

# round = arredonda o número para o número mais próximo
print(round(5.44, 1));
print(round(5.56, 1));